    % --- 1. 订单池 (这里模拟数据库中的原始数据) ---
    % 格式: {ID, 目标工位, 重量, 截止时间}
    % 规则: 
    %   - 目标 ID 1-12: 小配件 (需托举车 AGV Type 1)，重量 <= 50
    %   - 目标 ID 13-16: 大件 (需叉车 AGV Type 2)，重量 150~200
    raw_orders = [
        1,  5,   15,  200;  % 去5号 (小件)
        2,  14,  180, 500;  % 去14号 (大件)
        3,  2,   20,  220;  % 去2号 (小件)
