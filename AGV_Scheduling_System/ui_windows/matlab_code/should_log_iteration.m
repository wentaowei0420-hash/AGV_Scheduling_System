function tf = should_log_iteration(gen, max_gen, log_interval)
% =========================================================================
% 函数功能：判断当前代数是否应该输出详细日志
%
% 输入参数：
%   gen          - 当前进化代数（从 1 开始）
%   max_gen      - 最大进化代数
%   log_interval - 日志输出间隔（每隔多少代输出一次）
%
% 输出参数：
%   tf - 逻辑值，true 表示当前代数需要输出日志
%
% 输出规则：
%   以下三种情况之一满足时返回 true：
%   1. 第一代（gen == 1）    —— 输出初始状态
%   2. 最后一代（gen == max_gen） —— 输出最终结果
%   3. 当前代数是 log_interval 的倍数 —— 按间隔周期性输出
% =========================================================================
    tf = (gen == 1) || (gen == max_gen) || (mod(gen, log_interval) == 0);
end