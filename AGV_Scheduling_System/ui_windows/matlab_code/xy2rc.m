% =================================================================
% 工具函数：坐标转换器 (物理坐标 XY -> 矩阵索引 RowCol)
% 输入: [x, y] (物理坐标，从0开始)
% 输出: [row, col] (矩阵索引，从1开始)
% =================================================================
function rc = xy2rc(xy_list)
    % xy_list 可以是 n行2列 的矩阵
    % 第一列是 X，第二列是 Y
    
    % 矩阵行索引 (Row) = 物理 Y + 1
    rows = xy_list(:, 2) + 1;
    
    % 矩阵列索引 (Col) = 物理 X + 1
    cols = xy_list(:, 1) + 1;
    
    % 组合返回 [Row, Col]
    rc = [rows, cols];
end