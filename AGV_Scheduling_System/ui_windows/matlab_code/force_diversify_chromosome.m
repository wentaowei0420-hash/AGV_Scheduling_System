function chrom = force_diversify_chromosome(chrom, num_tasks, num_agvs)
% =========================================================================
% 函数功能：对染色体进行强制多样化操作，以避免个体与父代或另一个子代完全相同。
%           通过随机交换、片段翻转和随机重分配三种手段，显著改变染色体的
%           基因排列，提高种群多样性，防止早熟收敛。
%
% 输入参数：
%   chrom      - 待多样化的染色体向量（长度 2*num_tasks）
%                前半部分：任务执行顺序（1..num_tasks 的排列）
%                后半部分：对应任务的 AGV 指派（1..num_agvs 的整数）
%   num_tasks  - 任务总数
%   num_agvs   - 可用的 AGV 数量
%
% 输出参数：
%   chrom      - 经过强制多样化操作后的染色体（原地修改）
%
% 操作说明：
%   1. 随机交换两个任务顺序基因（如果任务数 >=2）
%      - 从任务顺序基因中随机挑选两个位置，交换它们的任务 ID。
%      - 简单有效，能立即改变任务执行顺序但不影响 AGV 指派。
%
%   2. 随机片段翻转（概率 0.7，且任务数 >=4）
%      - 在任务顺序基因中随机选取一段区间，将该区间内的基因顺序完全反转。
%      - 这是一种更强的扰动，能显著改变局部路径结构。
%      - 采用 70% 的概率是为了在大部分情况下都施加这种较大扰动，
%        但保留一定概率不操作，避免过度破坏。
%
%   3. 随机重分配 AGV 指派（任务数的 15%，至少 1 个，至多为全部任务）
%      - 从 AGV 指派基因段随机挑选一部分位置（ceil(0.15*num_tasks) 个），
%        将这些位置的指派值替换为新的随机 AGV 编号。
%      - 改变任务分配关系，能够产生全新的车辆负载模式。
%      - 操作比例控制在 15%，既保证足够的多样性，又不至于完全抹除
%        父代遗传下来的优良指派信息。
%
% 总体设计：
%   这三步措施层层递进，先小范围交换，再大概率区块翻转，最后局部重分配，
%   确保染色体从多个维度产生足够变化，从而脱离与父代或兄弟个体的完全相同状态。
% =========================================================================

    % ----- 第1步：随机交换两个任务顺序基因 -----
    if num_tasks >= 2
        % 随机选择两个不同的位置
        idx = randperm(num_tasks, 2);
        % 交换它们的基因值
        tmp = chrom(idx(1));
        chrom(idx(1)) = chrom(idx(2));
        chrom(idx(2)) = tmp;
    end

    % ----- 第2步：随机片段翻转（概率 0.7，且任务数 >=4）-----
    if num_tasks >= 4 && rand < 0.7
        % 随机确定翻转区间的两个端点，并排序
        seg = sort(randperm(num_tasks, 2));
        % 将区间内的元素反转
        chrom(seg(1):seg(2)) = fliplr(chrom(seg(1):seg(2)));
    end

    % ----- 第3步：随机重分配 AGV 指派 -----
    % 计算需要重新指派的基因个数（15% 的任务数，至少 1 个，至多为总任务数）
    assign_count = min(num_tasks, max(1, ceil(0.15 * num_tasks)));
    % 随机选择要修改的 AGV 指派位置（位于染色体后半段）
    assign_idx = randperm(num_tasks, assign_count);
    % 将这些位置的指派值随机设为 1..num_agvs 之间的整数
    chrom(num_tasks + assign_idx) = randi([1, num_agvs], 1, assign_count);
end