function unique_front = count_unique_front_objs(front_objs)
% =========================================================================
% 函数功能：统计第一前沿中去除量化重复后，实际唯一的目标值组合数量
%
% 输入参数：
%   front_objs  - 第一前沿个体的目标值矩阵（N × 3），列为 [距离, 时间, 能耗]
%
% 输出参数：
%   unique_front - 量化去重后，唯一的目标值组合个数（整数标量）
%
% 说明：
%   该函数通过 quantize_moo_objectives 对目标值进行不同精度的四舍五入，
%   然后再用 unique 按行去重，以消除因微小浮点误差造成的虚假差异，
%   从而真实反映前沿面上本质不同的解的数量。
% =========================================================================
    % 对目标值进行量化（四舍五入到指定精度），得到去重用的量化矩阵
    % unique 按行去重，'rows' 表示将每一行视为一个整体进行比较
    % size(..., 1) 返回去重后的行数，即唯一解的数量
    unique_front = size(unique(quantize_moo_objectives(front_objs), 'rows'), 1);
end