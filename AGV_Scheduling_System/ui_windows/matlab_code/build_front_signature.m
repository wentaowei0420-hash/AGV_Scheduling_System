function signature = build_front_signature(front_objs)
% =========================================================================
% 函数功能：构建前沿面的特征签名，用于检测代际停滞
%
% 输入参数：
%   front_objs - 当前代第一前沿所有个体的目标值矩阵（N × 3）
%
% 输出参数：
%   signature  - 该前沿的签名矩阵，由量化去重后、并按所有维度排序的唯一行组成
%
% 用途说明：
%   在 NSGA-II 中，需要判断相邻两代的第一前沿是否发生本质变化。
%   本函数通过 1) 量化去重消除数值噪声，2) 按行排序得到固定顺序的矩阵，
%   确保相同的多目标前沿面产生完全一致的签名矩阵。如果在多次迭代中
%   signature 保持不变，则判定为进化停滞，可触发移民或强化变异等策略。
% =========================================================================
    % 首先对目标值进行指定精度的量化（round）
    rounded_front = quantize_moo_objectives(front_objs);
    % unique 去除量化后完全相同的行（重复的解在签名中不重复出现）
    % sortrows 将唯一行按第1、2、3列排序，确保无论前沿面个体顺序如何，
    % 只要解集相同，签名矩阵就完全一致
    signature = sortrows(unique(rounded_front, 'rows'), [1 2 3]);
end