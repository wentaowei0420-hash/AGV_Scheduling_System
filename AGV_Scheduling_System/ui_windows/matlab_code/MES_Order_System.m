    % --- 2. 预处理与校验 ---
    % 在这里可以加入逻辑：比如过滤掉已经完成的订单，或者按紧急程度排序
    % 这里简单直接输出
    task_list = raw_orders;
    
    % --- 3. 生成统计摘要 (用于日志) ---
    small_parts = sum(task_list(:,2) <= 12);
    large_parts = sum(task_list(:,2) > 12);
    total_weight = sum(task_list(:,3));
    
    mes_summary.total_count = size(task_list, 1);
    mes_summary.type1_count = small_parts; % 适合托举车
    mes_summary.type2_count = large_parts; % 适合叉车
    mes_summary.total_weight = total_weight;
    
    disp(['>> [MES系统] 订单发布完成。共下发 ' num2str(mes_summary.total_count) ' 个任务。']);
    disp(['   - 小件任务(托举): ' num2str(small_parts)]);
    disp(['   - 大件任务(叉车): ' num2str(large_parts)]);
end