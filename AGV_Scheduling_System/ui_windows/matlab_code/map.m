%% 基于项目布局的MATLAB地图建模
% 图例对应区域编码：
% 0: 自由通道
% 1: 托架（共300个，排列成网格）
% 2: 托架式AGV充电桩
% 3: 叉车式AGV充电桩
% 4: 托架式AGV车库
% 5: 叉车式AGV车库
% 6: 相关配件仓库储存区域
% 7: 所需相关配件工位
% 8: 维修线
% 9: 障碍物（墙壁等不可通行区域）

clear; clc; close all;

%% 地图尺寸设定（根据托架数量和其他区域估算）
% 假设托架按15行×20列排列，共300个
rows = 50;   % 总行数
cols = 50;   % 总列数
map = zeros(rows, cols); % 初始化为自由通道

%% 1. 布置托架区域（编号1）
% 托架占据地图左上部分，每行20个，共15行
tray_rows = 15;
tray_cols = 20;
for i = 1:tray_rows
    for j = 1:tray_cols
        map(i, j) = 1;   % 托架位置
    end
end

%% 2. 布置充电桩、车库等其他设施（示例位置）
% 托架式AGV充电桩（2）放在托架区域右侧
map(5, 25) = 2;
map(6, 25) = 2;

% 叉车式AGV充电桩（3）
map(10, 25) = 3;
map(11, 25) = 3;

% 托架式AGV车库（4）
map(15, 25:28) = 4;

% 叉车式AGV车库（5）
map(20, 25:28) = 5;

% 相关配件仓库储存区域（6）
map(25:30, 30:35) = 6;

% 所需相关配件工位（7）
map(35:38, 30:35) = 7;

% 维修线（8）
map(40:45, 30:35) = 8;

% 障碍物（9）：例如墙壁边界或不可通行区域
map(1, :) = 9;          % 上边界
map(end, :) = 9;        % 下边界
map(:, 1) = 9;          % 左边界
map(:, end) = 9;        % 右边界
% 添加一些内部障碍（示例）
map(20:22, 10:12) = 9;

%% 3. 确保起点和终点可通行（示例，实际可根据需要设置）
% 通常AGV路径规划中起点和终点应为自由通道或托架等可通行区域
% 这里不设具体起点终点，仅展示地图

%% 4. 可视化地图
figure('Name', '项目布局地图', 'NumberTitle', 'off', 'Position', [100 100 800 600]);
imagesc(map);
colormap(gca, [1 1 1;      % 0 自由通道 - 白色
               0.5 0.5 0.5; % 1 托架 - 灰色
               1 0 0;       % 2 托架式AGV充电桩 - 红色
               0 1 0;       % 3 叉车式AGV充电桩 - 绿色
               0 0 1;       % 4 托架式AGV车库 - 蓝色
               1 1 0;       % 5 叉车式AGV车库 - 黄色
               1 0 1;       % 6 仓库 - 品红
               0 1 1;       % 7 工位 - 青色
               0.5 0 0.5;   % 8 维修线 - 紫色
               0 0 0]);     % 9 障碍物 - 黑色
colorbar('Ticks', 0:9, 'TickLabels', {'自由通道', '托架', '托架充电桩', '叉车充电桩', ...
                                      '托架车库', '叉车库', '仓库', '工位', '维修线', '障碍'});
axis equal tight;
title('项目布局栅格地图');

% 添加栅格线（可选）
ax = gca;
ax.XTick = 0.5:1:cols+0.5;
ax.YTick = 0.5:1:rows+0.5;
ax.XTickLabel = [];
ax.YTickLabel = [];
grid on;
ax.GridColor = [0.5 0.5 0.5];
ax.GridAlpha = 0.3;