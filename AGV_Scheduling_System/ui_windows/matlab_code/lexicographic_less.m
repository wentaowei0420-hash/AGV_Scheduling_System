function tf = lexicographic_less(a, b)
% =========================================================================
% 函数功能：字典序比较 —— 判断向量 a 是否在字典序上小于向量 b
%
% 输入参数：
%   a, b - 两个长度相同的数值向量（通常为 [时间, 距离, 能耗] 或其他优先顺序）
%
% 输出参数：
%   tf - 逻辑值，true 表示 a 字典序小于 b
%
% 字典序规则：
%   从第一个元素开始逐项比较：
%   - 若 a(i) < b(i) - 1e-9（显著小于），则 a < b，立即返回 true
%   - 若 a(i) > b(i) + 1e-9（显著大于），则 a 不 < b，立即返回 false
%   - 若两者差异在容差内（视为相等），则继续比较下一个元素
%   如果所有元素都视为相等，则 a 不 < b，返回 false
%
% 容差 1e-9 用于处理浮点误差，避免微小数值差异影响比较结果。
%
% 在代码中的用途：
%   通常用于瓶颈转移选择（choose_best_fork_transfer），以 [时间, 距离, 能耗]
%   的顺序择出综合最优的转移方式，时间优先、距离次之、能耗最后考虑。
% =========================================================================
    tf = false;
    for i = 1:numel(a)
        if a(i) < b(i) - 1e-9
            tf = true;
            return;       % a 的当前元素显著小于 b，a 字典序 < b
        elseif a(i) > b(i) + 1e-9
            return;       % a 的当前元素显著大于 b，a 不 < b，函数返回 false
        end
        % 若相等（差异在容差内），继续比较下一个元素
    end
    % 循环结束意味着所有元素都相等，a 不严格小于 b，返回 false
end