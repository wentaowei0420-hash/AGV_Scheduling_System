function rounded_objs = quantize_moo_objectives(pop_objs)
% =========================================================================
% 函数功能：将多目标值进行不同精度的量化（四舍五入），用于去重比较
%
% 输入参数：
%   pop_objs  - 种群目标值矩阵（任意行数 × 3），列为 [距离, 时间, 能耗]
%
% 输出参数：
%   rounded_objs - 同样大小的矩阵，但各列按照指定精度四舍五入：
%                  第1列（距离）   保留 0 位小数（四舍五入到整数）
%                  第2列（时间）   保留 2 位小数
%                  第3列（能耗）   保留 4 位小数
%
% 设计意图：
%   距离（通常很大）取整即可区分；时间精确到百分秒；能耗（单位小）保留 4 位小数。
%   这种差异化的量化精度旨在识别“实质上相同”的解，避免因极小的浮点误差
%   导致 unique 产生大量伪不同解，从而影响多样性评估和去重逻辑。
% =========================================================================
    rounded_objs = [round(pop_objs(:, 1), 0), round(pop_objs(:, 2), 2), round(pop_objs(:, 3), 4)];
end